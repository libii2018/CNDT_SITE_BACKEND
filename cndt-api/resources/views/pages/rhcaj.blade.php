          <div class="page-heading">
            <div>
              <h2>Commission des Ressources Humaines, de la Coopération &amp; des Affaires Juridiques</h2>
            </div>
          </div>

          <div class="org-intro">
            <p>
              Placée sous l'autorité d'un <strong>Coordonnateur Exécutif Adjoint</strong>, la
              Commission des Ressources Humaines, de la Coopération et des Affaires Juridiques est
              chargée de la mise en œuvre de la stratégie de coopération et de partenariat du Comité
              National de Développement des Technologies, du suivi de la coopération bilatérale et
              multilatérale, de la gestion prévisionnelle des effectifs, des plans de formation, ainsi
              que de la défense des intérêts juridiques du CNDT.
            </p>
            <p style="margin-top:14px;">
              Elle est structurée en <strong>trois Secrétariats techniques</strong> :
              le <strong>Secrétariat de la Coopération et du Partenariat</strong>, le
              <strong>Secrétariat des Ressources Humaines</strong> et le
              <strong>Secrétariat Juridique et du Contentieux</strong>.
            </p>
          </div>

          <!-- =========================================================
               ATTRIBUTIONS DE LA COMMISSION
               ========================================================= -->
          <div class="page-heading" style="margin-top:56px;">
            <div>
              <h2>Ce dont la Commission est chargée</h2>
            </div>
          </div>

          <ul class="project-list" style="columns:2; column-gap:34px;">
            <li>De la mise en œuvre de la stratégie de coopération et de partenariat ;</li>
            <li>Du suivi de la coopération bilatérale et multilatérale aux niveaux national et international ;</li>
            <li>De l'élaboration et du suivi des conventions et accords concernant le développement et le transfert des technologies ;</li>
            <li>De la promotion et du suivi des relations de partenariat avec les organismes gouvernementaux et non-gouvernementaux s'occupant du développement et du transfert des technologies ;</li>
            <li>De la participation à la recherche des financements et de l'expertise technique requise pour les projets et programmes du CNDT ;</li>
            <li>De la mise en place et de la gestion d'une banque de données sur les partenaires techniques et financiers ;</li>
            <li>De la participation à la préparation de toutes manifestations promotionnelles relatives aux activités en lien avec les missions du CNDT ;</li>
            <li>De la participation à l'organisation des journées portes ouvertes, des foires et des expositions des produits de la recherche ;</li>
            <li>De la gestion prévisionnelle des effectifs, en liaison avec la Sous-direction des Personnels, de la Solde et des Pensions du Ministère chargé de la Recherche Scientifique ;</li>
            <li>De l'élaboration des plans de formation et du recyclage des personnels ;</li>
            <li>Du contrôle permanent des présences et de la discipline ;</li>
            <li>De la préparation et de l'instruction des dossiers disciplinaires des personnels ;</li>
            <li>De la préparation et du suivi des dossiers de sécurité sociale du personnel ;</li>
            <li>De la centralisation des besoins en formation ;</li>
            <li>De la tenue des fichiers des stagiaires ;</li>
            <li>De l'étude de tous les dossiers relatifs aux contentieux opposant le CNDT aux tiers ;</li>
            <li>Du conseil juridique sur toute question intéressant le Comité — le cas échéant, il peut se faire assister par un conseil d'avocat requis par le Secrétaire Permanent ;</li>
            <li>De la défense des intérêts du CNDT en justice et en tout lieu, en liaison avec la Cellule Juridique du Ministère en charge de la Recherche Scientifique et de l'Innovation ;</li>
            <li>De la préparation et de la mise en forme de tous les projets de texte de nature législative, réglementaire et conventionnelle ;</li>
            <li>De l'application des procédures, accords, contrats et conventions.</li>
          </ul>

