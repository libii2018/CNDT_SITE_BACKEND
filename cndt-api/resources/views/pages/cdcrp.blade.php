          <div class="page-heading">
            <div>
              <h2>La Commission Documentation, Communication &amp; Relations Publiques</h2>
            </div>
          </div>

          <div class="org-intro">
            <p>
              Placée sous l'autorité d'un <strong>Coordonnateur Exécutif Adjoint</strong>, la Commission
              Documentation, Communication et Relations Publiques est chargée de la gestion de la
              documentation scientifique et technique du Comité National de Développement des
              Technologies, de la conception et de la diffusion des supports de communication, ainsi
              que de la promotion de l'image et des activités du CNDT auprès des médias, des partenaires
              et du grand public.
            </p>
            <p style="margin-top:14px;">
              Elle anime également le site web institutionnel, le système d'archivage numérique et la
              bibliothèque du Comité, en liaison avec la Cellule Informatique. Elle constitue ainsi le
              cœur informationnel et communicationnel du CNDT.
            </p>
          </div>

          <!-- =========================================================
               ATTRIBUTIONS DE LA COMMISSION
