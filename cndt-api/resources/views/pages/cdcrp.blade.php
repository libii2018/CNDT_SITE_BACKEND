              <h2>Ce dont la Commission est chargée</h2>
            </div>
          </div>

          <ul class="project-list" style="columns:2; column-gap:34px;">
            <li>De la gestion de la documentation scientifique et technique ;</li>
            <li>De la tenue de l'inventaire de la documentation ;</li>
            <li>De la bonne conservation de la documentation, de son enregistrement et de son indexation ;</li>
            <li>De l'exploitation des documents stratégiques, techniques et opérationnels ;</li>
            <li>De l'organisation du système d'archivage numérique de la documentation produite au CNDT ;</li>
            <li>De l'organisation et du fonctionnement de la bibliothèque du CNDT ;</li>
            <li>De la conservation de la documentation numérique et des informations scientifiques virtuelles, en liaison avec la Cellule Informatique ;</li>
            <li>De la mise en place, du suivi et de la mise à jour de la bibliothèque ;</li>
            <li>De la préparation, de la conception et de la réalisation de tous les supports de communication destinés aux usagers du CNDT (magazines, bulletins, plaquettes, agendas, calendriers, répertoires, oriflammes, etc.) ;</li>
            <li>De la conception des contenus de communication de masse à diffuser dans les réseaux sociaux et les médias ;</li>
            <li>De l'animation du site web du CNDT ;</li>
            <li>De la promotion de l'image et des activités du CNDT ;</li>
            <li>Du développement et de la gestion des relations avec les médias et la presse ;</li>
            <li>De l'organisation et de la gestion de l'évènementiel.</li>
          </ul>

